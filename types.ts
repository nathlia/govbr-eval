// ── Adjudication (D-21) ───────────────────────────────────────────────────────

/**
 * What a human decided about an agent finding that matched no expected unit.
 *
 *   falso-positivo   the agent was wrong — charged to precision
 *   lacuna-gabarito  a real violation the gabarito never catalogued — excluded from FP and
 *                    tracked as owed gabarito work (the unit only exists once it is written
 *                    into ground-truth.json WITH measured baselines, D-06)
 *   vocabulario      the right defect under a name the scorer does not know — becomes an
 *                    adjudicated match for the unit named in `unit`
 *   deteccao-correta the finding describes the target unit, but its citation or anchoring was
 *                    not mechanically valid — detection is credited; grounding is not
 *   duplicado        a restatement of another finding already matched on the same case
 *   indeterminado    reviewed, undecidable — stays charged as FP so the floor is never
 *                    improved by indecision
 *   composto         the claim asserts MORE THAN ONE defect, and the parts do not share a
 *                    verdict — decided per part in `components` (D-30)
 */
export type AdjudicationVerdict =
  | "falso-positivo"
  | "lacuna-gabarito"
  | "vocabulario"
  | "deteccao-correta"
  | "duplicado"
  | "indeterminado"
  | "composto";

/** A verdict a component of a compound claim can carry — `composto` never nests (D-30). */
export type ComponentVerdict = Exclude<AdjudicationVerdict, "composto">;

/**
 * One defect asserted inside a compound claim (D-30).
 *
 * The vocabulary before D-30 assumed one claim carried one defect, so a finding that named both
 * a catalogued unit and an uncatalogued violation had no truthful verdict: `vocabulario` hid the
 * gap, `lacuna-gabarito` discarded the credit, and the two errors biased the number in opposite
 * directions. Splitting the record is what lets both halves be recorded as what they are.
 */
export interface AdjudicationComponent {
  verdict: ComponentVerdict;
  /** Required for `vocabulario` and `deteccao-correta`, exactly as on a simple record. */
  unit?: { caseId: string; rule: RuleId };
  /** Why THIS part got THIS verdict. Required — same rule as a simple record. */
  rationale: string;
  /** For `lacuna-gabarito` components: has the unit been written into the gabarito yet? */
  gabaritoStatus?: "pendente" | "incorporada";
}

export interface AdjudicationRecord {
  /** Stable id: `<caseId>:<8 hex of sha256 over the normalized finding text>` (D-21). */
  id: string;
  caseId: string;
  /** The finding text as archived, for a human reading this file. Never used for matching. */
  finding: string;
  /** Runs the finding appears in, filled by `npm run adjudicate -- --emit`. Provenance only. */
  seenIn?: { run: string; arm: string }[];
  /** null = stub emitted, not yet decided. Stubs are counted as pending, never applied. */
  verdict: AdjudicationVerdict | null;
  /** Required for `vocabulario` and `deteccao-correta`: the expected unit actually reported. */
  unit?: { caseId: string; rule: RuleId };
  /**
   * Required for `composto`, forbidden otherwise: the defects this claim asserts, judged one by
   * one (D-30). At least two — a single component is a simple record wearing a compound label.
   */
  components?: AdjudicationComponent[];
  /** Why. Required for every decided record — a verdict without a reason is not adjudication. */
  rationale?: string;
  adjudicatedBy?: string;
  adjudicatedAt?: string;
  /**
   * Exposição declarada de quem julgou (D-33): a spec do gabarito que essa pessoa já tinha
   * discutido antes de julgar — ex.: `"V-07 (D-32)"`. Não invalida o veredito e não muda a
   * pontuação; torna legível para a banca de onde vem o julgamento. Ausente = sem exposição
   * conhecida. Ver `docs/adjudicacao.md § Quem pode julgar`.
   */
  exposicao?: string;
  /**
   * Ajuda que pode ter moldado o veredito, declarada mesmo sem proposta formal — ex.: definições
   * explicadas, leitura confirmada, razão redigida a partir das palavras de quem julgou. Não muda a
   * pontuação. Ausente junto com `proposta` = sem ajuda. Ver `docs/adjudicacao.md § O que o
   * assistente pode fazer`.
   */
  apoio?: string;
  /**
   * O que o assistente propôs, gravado separado da decisão: só o rótulo dentro do crédito
   * (`vocabulario`/`deteccao-correta`) e a unidade — a classe de efeito é sempre de quem julga.
   * Quando `proposta.verdict` difere de `verdict`, a troca fica visível.
   */
  proposta?: {
    por: "assistente";
    verdict: "vocabulario" | "deteccao-correta";
    unit?: { caseId: string; rule: RuleId };
    em: string;
  };
  /**
   * Registro aposentado: a alegação existiu, mas deixou de ser sobra sob o instrumento e o
   * gabarito vigentes, e por isso não é mais julgável nem contada como pendente. NUNCA é apagada
   * — a aposentadoria é reversível em princípio, e o motivo viaja com ela. Um registro aposentado
   * não carrega `verdict`: ninguém o julgou, e fingir que sim inventaria uma adjudicação.
   *
   * `porque` diz o que o deslocou (a execução saiu do instrumento; o gabarito passou a casar a
   * alegação); `decisao` cita a entrada do log que produziu o deslocamento, quando houver.
   */
  retirada?: { em: string; porque: string; decisao?: string };
  /** For `lacuna-gabarito`: has the unit been written into ground-truth.json yet? */
  gabaritoStatus?: "pendente" | "incorporada";
}

export interface Adjudications {
  _meta: Record<string, unknown>;
  adjudications: AdjudicationRecord[];
}

// ── Suíte de fluxo (D-23): unidades ancoradas em elemento ────────────────────

/**
 * Uma violação da página-fluxo, declarada por SELETOR e não por seção.
 *
 * A suíte `TC-*` ancora unidade em seção (`TC-B-08`), o que só funciona porque cada seção contém
 * um espécime e um defeito. Numa tela de serviço de verdade as seções deixam de existir como
 * recorte natural, e o caso decisivo do D-23 — a violação que TODAS as instâncias compartilham —
 * é irrepresentável nesse esquema: numa seção só, "todos os botões estão errados" vale uma
 * unidade, e o agente acerta dizendo isso uma vez. O que se quer medir é se ele ENUMERA as
 * instâncias, e isso exige unidade por elemento.
 */
export interface FlowViolationSpec {
  /** V-01, V-02 … — identidade da especificação, não da unidade (uma spec vira N unidades). */
  id: string;
  /** Seletor CSS resolvido na página viva. */
  anchor: string;
  /** Elementos a subtrair da resolução do `anchor`. */
  except?: string;
  /**
   * "unico"      — deve resolver para exatamente um elemento;
   * "todos"      — vira uma unidade por elemento resolvido (a violação compartilhada do D-23);
   * "composicao" — o `anchor` resolve para TODOS os participantes do defeito, e a spec vale UMA
   *                unidade (D-33). É a ponta do gabarito do que o D-29 resolveu na ponta do
   *                achado: aqui o número de elementos resolvidos deixa de ser o número de
   *                unidades. Use quando o defeito é propriedade do conjunto e um único conserto
   *                o repara — a semântica de lista ausente do V-04 —, nunca quando cada elemento
   *                carrega o defeito por si (aí é `todos`, e a enumeração é o que se cobra).
   */
  scope: "unico" | "todos" | "composicao";
  /**
   * Quantas UNIDADES a spec vale. Em `unico`/`todos` é também o número de elementos resolvidos, e
   * quando a página discorda a pontuação PARA em vez de medir — é o guarda contra editar a tela e
   * esquecer o gabarito (D-06). Em `composicao` vale sempre 1, e quem responde pela contagem de
   * elementos é `participantCount`.
   */
  expectedCount?: number;
  /**
   * Só em `composicao`: quantos elementos o gabarito afirma participarem do defeito. Medido na
   * página viva, nunca deduzido; se a página discordar, a pontuação para pelo mesmo motivo que
   * `expectedCount` (D-06).
   */
  participantCount?: number;
  /**
   * Viewport em que a violação se manifesta, quando não é a padrão da suíte (D-35).
   *
   * É propriedade de ONDE O DEFEITO APARECE, não da identidade do elemento: a âncora segue sendo
   * resolvida no viewport padrão, porque o elemento é o mesmo objeto da árvore nos dois tamanhos.
   * Quem obedece a este campo é a MEDIÇÃO — a linha de base roda uma passada por viewport
   * declarado, senão cobraria do axe um defeito que ele não tinha como ver.
   *
   * Se algum dia uma spec ancorar em elemento que só EXISTE no viewport declarado, a âncora não
   * resolve e o guarda de `expectedCount` para a pontuação em vez de medir (D-06) — falha ruidosa,
   * que é o comportamento desejado até o resolvedor também passar a respeitar o campo.
   */
  viewport?: FlowViewport;
  /** Estado observável em que a unidade deve ser alcançada (ex.: `sempre`, `apos-submit-vazio`). */
  state?: string;
  /** A unidade só existe no estado declarado; nunca é presumida no primeiro paint. */
  conditional?: boolean;
  /** O baseline deve provar que o scanner determinístico detecta esta spec antes de medir. */
  deterministicBaseline?: boolean;
  /**
   * Condição MECÂNICA sob a qual o defeito desta spec existe na página (fatia 3).
   *
   * Declarar isto tira a spec do território da pura autoria: a preparação mede a condição na
   * página congelada, no estado declarado, e PARA se o que o gabarito afirma não estiver lá. É a
   * resposta possível ao fato de que a tela e o gabarito foram redigidos pelo assistente, que a
   * regra de independência desqualifica para julgar sobre eles.
   *
   * O que o predicado NÃO faz: creditar. Sustentar prova que o defeito existe, nunca que a
   * alegação do agente afirma esse defeito — essa ponte é decisão semântica da autora (D-39).
   * Spec sem `acceptance` fica `nao-implementado`, e isso jamais vira aceitação por elemento.
   */
  acceptance?: FlowAcceptancePredicate;
  /** Aliases normativos: o achado casa citando QUALQUER um deles. */
  rules: RuleId[];
  categories: string[];
  description: string;
}

/**
 * Predicado de aceitação declarado por uma spec. A semântica de cada espécie, e por que este
 * avaliador não reaproveita os verificadores do oráculo, estão em `scripts/acceptance-predicates.ts`.
 */
export interface FlowAcceptancePredicate {
  kind: string;
  properties?: string[];
  attributes?: string[];
  /** Conjunto admissível pela NORMA: sustenta quando o medido cai fora. Forma preferida. */
  allowed?: string[];
  /** Valor autoral que o gabarito acusa: sustenta quando o medido cai dentro. Exige `note`. */
  forbidden?: string[];
  quantifier?: "alguma" | "todas";
  classe?: string;
  tag?: string;
  /** De onde vem o valor esperado. Obrigatório com `forbidden`. */
  note?: string;
}

/**
 * Um passo de preparação da página antes da resolução de âncoras.
 *
 * `navigate` (tela B, D-57) é a navegação DENTRO da aplicação: troca de rota sem recarregar o
 * documento, pelo clique num alvo (`selector`) OU por um caminho da mesma origem (`path`, aplicado
 * com `history.pushState` + `popstate`, que é o que o roteador da SPA escuta). Nunca recarrega:
 * recarregar zeraria o backend em memória e mediria um estado que o setup não descreve. Exige
 * `waitFor`, o seletor que prova que a rota nova pintou. Cada `navigate` abre um SEGMENTO novo da
 * sequência: a aditividade só é cobrada dentro de um segmento (ver `_meta.states`).
 */
export interface FlowSetupStep {
  action: "click" | "fill" | "wait" | "navigate";
  /** Alvo de `click`/`fill`, seletor a aguardar em `wait`, ou alvo do clique de `navigate`. */
  selector?: string;
  /** Texto de `fill`. */
  value?: string;
  /** Milissegundos de `wait` quando não há seletor. */
  ms?: number;
  /** `navigate` sem clique: caminho absoluto (`/…`) na MESMA origem da entrada. */
  path?: string;
  /** `navigate`: seletor que tem de existir depois da troca de rota. Obrigatório. */
  waitFor?: string;
}

/** Tamanho de janela em que uma unidade é medida. */
export interface FlowViewport {
  width: number;
  height: number;
}

export interface FlowGroundTruth {
  _meta: {
    /** Identificador da página-fluxo, usado como prefixo de proveniência. */
    page: string;
    /** Caminho relativo ao APP_URL. */
    url: string;
    /** Seletor a aguardar antes de resolver âncoras (a tela é uma SPA). */
    waitFor?: string;
    /**
     * Interações aplicadas ANTES de resolver as âncoras, para alcançar violações que só passam a
     * existir depois de um uso da tela (mecanismo que o D-22 apontou como ausente no corpus).
     *
     * A sequência tem de ser ADITIVA: pode fazer nascer elementos, nunca destruir os que o
     * gabarito já ancora. Se um passo removesse um elemento, as duas metades do gabarito
     * passariam a descrever estados diferentes da página e nada acusaria.
     *
     * Com `navigate` (D-57) a promessa vale POR SEGMENTO: entre paradas sem navegação no meio.
     */
    setup?: FlowSetupStep[];
    /**
     * Paradas nomeadas dentro de `setup`, em que as âncoras são resolvidas.
     *
     * É o que transforma o campo `state` de cada spec, até aqui um rótulo que nenhum código lia,
     * em algo que a página responde: resolvendo em cada parada dá para dizer em QUE estados cada
     * elemento existe, conferir a aditividade prometida em `setup_rationale` e cobrar o
     * `conditional` de quem declara nascer depois de uma interação.
     *
     * `afterStep` é um índice na sequência de `setup` — nunca uma segunda cópia dela, para que o
     * gabarito e o resolvedor não possam discordar sobre o que um estado quer dizer. O primeiro
     * estado declarado deve ser o primeiro paint (`afterStep: 0`).
     *
     * `path` é o caminho da barra de endereço (só `pathname`) em que a parada tem de estar. É
     * OBRIGATÓRIO em todas as paradas quando o `setup` tem algum `navigate` — a navegação troca a
     * árvore inteira, e é o endereço que diz de qual rota a parada fala; sem navegação é opcional.
     * Em ambos os casos, se declarado, é conferido contra a página.
     */
    states?: { id: string; afterStep: number; note?: string; path?: string }[];
    /**
     * Viewport padrão da suíte, em que toda spec que não declara `viewport` é medida.
     *
     * Estava implícito e DIVERGENTE: o runner de linha de base abria 1280×900 e o resolvedor de
     * âncoras usava o padrão do Playwright (1280×720). Para as unidades de hoje a altura não muda
     * nada, mas era mais uma dimensão que uma parte do código conhecia e a outra não — o defeito
     * que o log acompanha desde o D-13. Declarado aqui, os dois leem o mesmo número.
     */
    viewport?: FlowViewport;
    [k: string]: unknown;
  };
  violations: FlowViolationSpec[];
}

/**
 * Um achado do agente na suíte de fluxo. Sem id de caso: não há grade de correção para percorrer,
 * o agente diz ONDE olhando para a página. Um seletor que resolve para k elementos é k afirmações
 * da mesma regra — é assim que "todos os botões têm o raio errado" credita todas as instâncias de
 * uma vez, e é também por isso que um seletor largo demais paga em precisão.
 */
export interface FlowFinding {
  selector: string;
  /**
   * Outros participantes necessários para sustentar um defeito relacional. Eles fornecem
   * contexto de ancoragem, mas não multiplicam o achado em novas afirmações.
   */
  relatedSelectors?: string[];
  /** Norma citada. `null` quando o agente declara a atribuição incerta (fluxo-1.3.0). */
  rule: RuleId | null;
  /** Até fluxo-1.2.0, observação e justificativa num texto só. No contrato novo é opcional. */
  description?: string;
  /** fluxo-1.3.0: o que a inspeção mostrou — valor, texto, atributo ou comportamento. */
  observed?: string;
  /** fluxo-1.3.0: a condição que deveria valer. */
  expected?: string;
  /** fluxo-1.3.0: janela e interações que produziram o estado observado. */
  state?: FlowFindingState;
  /** fluxo-1.3.0: caminhos ou identificadores devolvidos pelas ferramentas. */
  evidence?: string[];
}

/**
 * Estado em que um achado foi observado, nas palavras do agente: a janela e as interações desde o
 * carregamento. Nunca um id de estado do gabarito — o agente não conhece nenhum.
 */
export interface FlowFindingState {
  viewport: FlowViewport;
  steps: string[];
}

/**
 * Registro que o coletor grava num relatório promovido (surface-1.2.0): a execução nunca teve
 * relatório aceito, e a última tentativa recusada virou o relatório dela. Nunca satisfaz o contrato
 * de coleta; o pacote de revisão rotula seus achados como `recusado` ou `malformado`.
 */
export interface FlowCollectorRecord {
  status: "recusa-arquivada";
  /** Motivo da última recusa, como o coletor respondeu ao agente. */
  reason: string;
  /** Arquivo em `rejected/` que foi promovido. */
  rejectedFile: string;
  refusedAt: string;
  promotedAt: string;
  /** Objeto JSON com lista `findings`: os achados seguem à revisão, sinalizados. */
  parseable: boolean;
  /** Campos de topo preenchidos com o que o próprio coletor sabe (`findings`, `timestamp`, `appUrl`). */
  filled: string[];
  /** O corpo recusado, byte a byte. */
  rawBody: string;
  satisfiesContract: false;
}

export interface FlowAgentResults {
  timestamp: string;
  model: string;
  appUrl: string;
  config?: RunConfig;
  cost?: AgentRunCost;
  /** O que o agente declara ter inspecionado. Proveniência apenas — não entra na pontuação. */
  scope?: string[];
  findings: FlowFinding[];
  /** Somente em relatório promovido pelo coletor; campo do coletor, descartado se o agente o enviar. */
  collector?: FlowCollectorRecord;
}
