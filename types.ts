/** Shared data model: ground truth (gabarito) and generated result files. */

/** true = tool detects; false = tool misses; null = reference case (no violation expected) */
export type Detection = boolean | null;

export type ToolKey = "axe" | "eslint_a11y" | "agent";

/**
 * Rule id vocabulary (E3 matching):
 *   govbr-<dsVersion>-…  KB deterministic id (first-class since Phase 3.1) — PREFERRED when the
 *                        violated rule came from the oracle's get_ds_rules; matched by exact id
 *                        equality, and translated to/from emag:/wcag: aliases via kb-aliases.json
 *                        (generated by scripts/generate-kb-aliases.ts — never hand-edited)
 *   emag:<section>       e.g. "emag:6.5"
 *   wcag:<sc>            e.g. "wcag:3.3.2"
 *   ds:<rule>            token-color | token-font | token-radius | token-focus | token-spacing |
 *                        button-order | component-structure | form-label
 */
export type RuleId = string;

export interface GroundTruthViolation {
  description: string;
  /** Normative rule aliases — a finding matches this violation if it cites ANY of them. */
  rules: RuleId[];
  categories: string[];
}

export interface GroundTruthCase {
  page:
    | "buttons"
    | "forms"
    | "nav"
    | "table"
    | "list"
    | "interactive"
    | "static-refresh"
    | "static-layering"
    | "static-clean";
  description: string;
  violations: GroundTruthViolation[];
  /** Union of the violations' categories (kept for display/back-compat). */
  categories: string[];
  detection: Record<ToolKey, Detection>;
  notes?: string;
}

export interface GroundTruth {
  _meta: Record<string, unknown>;
  cases: Record<string, GroundTruthCase>;
}

/**
 * Organic wing (D-13): defects that exist in the official package's own
 * canonical examples, rendered verbatim. Separate suite — its metrics are
 * NEVER pooled with the injected corpus.
 */
export interface OrganicGroundTruthCase extends Omit<GroundTruthCase, "page"> {
  page: "organic";
  /** Package-relative path of the fragment rendered verbatim. */
  fragment: string;
  /** sha256 of the installed file, matching the KB package audit. */
  sourceSha256: string;
  /** Finding id in the KB's official-package-audit.json. */
  auditFindingId: string;
}

export interface OrganicGroundTruth {
  _meta: Record<string, unknown>;
  cases: Record<string, OrganicGroundTruthCase>;
}

export interface AxeViolationRef {
  rule: string;
  impact?: string;
  description: string;
  helpUrl?: string;
}

export interface AxePageResult {
  passes: number;
  violationCount: number;
  byCaseId: Record<string, AxeViolationRef[]>;
  /** axe "needs review" results — informational only, never counted as detections. */
  incompleteByCaseId?: Record<string, AxeViolationRef[]>;
  raw?: unknown;
}

export interface AxeResults {
  timestamp: string;
  tool: string;
  appUrl: string;
  results: Record<string, AxePageResult>;
}

/**
 * One agent finding. Preferred (v2.1+): structured object with a rule id from the vocabulary.
 * Legacy (pilot runs): plain string — rule ids are parsed from the normative citations in the text.
 */
export type AgentFinding = string | { rule: RuleId; description: string };

export interface AgentVerdict {
  detected: boolean;
  violations_found: AgentFinding[];
  notes?: string;
}

/** Cost accounting for one evaluation run (F4). */
export interface AgentRunCost {
  startedAt: string;
  finishedAt: string;
  wallClockSeconds: number;
  /** Total MCP/browser tool calls made during the run (approximate is fine). */
  toolCalls?: number;
  /** Total tokens if the client reports them (e.g. /cost in Claude Code). */
  tokens?: number;
  notes?: string;
}

/**
 * Configuration label for an archived run (D-17). Optional: when absent, the scorer falls back to
 * the directory convention (results/runs = com oráculo, results/runs-ablacao = sem oráculo).
 * Corpus coverage is never taken from here — it is derived from the verdicts themselves.
 */
export interface RunConfig {
  /** "com-oraculo" (padrão) ou "sem-oraculo" (braço da ablação, F2). */
  arm?: string;
  /** Rótulo livre, e.g. "piloto". */
  label?: string;
}

export interface AgentResults {
  timestamp: string;
  model: string;
  appUrl: string;
  config?: RunConfig;
  _empty?: boolean;
  cost?: AgentRunCost;
  verdicts: Record<string, AgentVerdict>;
}

/** Measured eslint-plugin-jsx-a11y baseline (F2). */
export interface EslintFindingRef {
  rule: string;
  message: string;
  file: string;
  line: number;
}

export interface EslintResults {
  timestamp: string;
  tool: string;
  config: string;
  filesLinted: string[];
  byCaseId: Record<string, EslintFindingRef[]>;
  /** Findings that could not be attributed to a TC-* section. */
  unattributed: EslintFindingRef[];
}

// ── Adjudication (D-21) ───────────────────────────────────────────────────────

/**
 * What a human decided about an agent finding that matched no expected unit.
 *
 *   falso-positivo   the agent was wrong — charged to precision
 *   lacuna-gabarito  a real violation the gabarito never catalogued — excluded from FP and
 *                    tracked as owed gabarito work (the unit only exists once it is written
 *                    into ground-truth.json WITH measured baselines, D-06)
 *   vocabulario      the right defect under a name the scorer does not know — becomes an
 *                    adjudicated match for the unit named in `unit`
 *   duplicado        a restatement of another finding already matched on the same case
 *   indeterminado    reviewed, undecidable — stays charged as FP so the floor is never
 *                    improved by indecision
 */
export type AdjudicationVerdict =
  | "falso-positivo"
  | "lacuna-gabarito"
  | "vocabulario"
  | "duplicado"
  | "indeterminado";

export interface AdjudicationRecord {
  /** Stable id: `<caseId>:<8 hex of sha256 over the normalized finding text>` (D-21). */
  id: string;
  caseId: string;
  /** The finding text as archived, for a human reading this file. Never used for matching. */
  finding: string;
  /** Runs the finding appears in, filled by `npm run adjudicate -- --emit`. Provenance only. */
  seenIn?: { run: string; arm: string }[];
  /** null = stub emitted, not yet decided. Stubs are counted as pending, never applied. */
  verdict: AdjudicationVerdict | null;
  /** Required for `vocabulario`: the expected unit this finding actually reported. */
  unit?: { caseId: string; rule: RuleId };
  /** Why. Required for every decided record — a verdict without a reason is not adjudication. */
  rationale?: string;
  adjudicatedBy?: string;
  adjudicatedAt?: string;
  /** For `lacuna-gabarito`: has the unit been written into ground-truth.json yet? */
  gabaritoStatus?: "pendente" | "incorporada";
}

export interface Adjudications {
  _meta: Record<string, unknown>;
  adjudications: AdjudicationRecord[];
}
